-- ------------------------------------------------------------
-- 1. Pump fields on readings (reported by the ESP32 itself)
--    pump_status           = ACTUAL relay state, not the requested one
--    control_mode          = AUTO | MANUAL (mode currently running)
--    pump_runtime_seconds  = current continuous run duration
-- ------------------------------------------------------------
alter table public.readings
  add column if not exists pump_status boolean;
alter table public.readings
  add column if not exists control_mode text;
alter table public.readings
  add column if not exists pump_runtime_seconds integer;

-- ------------------------------------------------------------
-- 2. device_commands — one CURRENT command per device
--    mode  pump   meaning
--    AUTO  OFF    → ESP32 controls the pump from the water level
--    MANUAL ON   → request pump ON until expiry or safety cutoff
--    MANUAL OFF  → request pump OFF
--    Switching to AUTO always stores pump = 'OFF' (ignored in AUTO).
-- ------------------------------------------------------------
create table if not exists public.device_commands (
  id              bigint generated by default as identity primary key,
  device_code     text not null unique,
  mode            text not null default 'AUTO'
                  check (mode in ('AUTO', 'MANUAL')),
  pump            text not null default 'OFF'
                  check (pump in ('ON', 'OFF')),
  updated_at      timestamptz not null default now(),
  expires_at      timestamptz,
  updated_by      uuid references auth.users (id),
  acknowledged_at timestamptz
);

-- ------------------------------------------------------------
-- 3. pump_events — ACTUAL pump transitions recorded once each
--    (written by the readings ingest route when the device reports
--     a change of the real pump state — never on button clicks)
--    stop_reason examples: TARGET_REACHED, MANUAL_OFF, SENSOR_INVALID,
--    MAX_RUNTIME, COMMAND_EXPIRED, DEVICE_REBOOT, SAFETY_CUTOFF
-- ------------------------------------------------------------
create table if not exists public.pump_events (
  id              bigint generated by default as identity primary key,
  device_code     text not null,
  event_type      text not null check (event_type in ('STARTED', 'STOPPED')),
  occurred_at     timestamptz not null default now(),
  runtime_seconds integer,
  stop_reason     text
);

create index if not exists pump_events_device_time_idx
  on public.pump_events (device_code, occurred_at desc);

-- ------------------------------------------------------------
-- 4. Row Level Security — a user sees only their own rows.
--    There are deliberately NO browser write policies:
--      - device_commands is written only by POST /api/pump-command
--        (authenticated route + service role, ownership verified);
--      - pump_events is written only by the ingest API (service role).
-- ------------------------------------------------------------
alter table public.device_commands enable row level security;
alter table public.pump_events     enable row level security;

drop policy if exists commands_select_own on public.device_commands;
create policy commands_select_own on public.device_commands
  for select using (
    exists (
      select 1 from public.devices d
      where d.device_code = device_code
        and d.user_id = auth.uid()
    )
  );

drop policy if exists pump_events_select_own on public.pump_events;
create policy pump_events_select_own on public.pump_events
  for select using (
    exists (
      select 1 from public.devices d
      where d.device_code = device_code
        and d.user_id = auth.uid()
    )
  );

-- ------------------------------------------------------------
-- 5. Realtime — publish the new tables (RLS-filtered automatically)
-- ------------------------------------------------------------
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    begin
      alter publication supabase_realtime add table public.device_commands;
    exception when duplicate_object then null; -- already added
    end;
    begin
      alter publication supabase_realtime add table public.pump_events;
    exception when duplicate_object then null;
    end;
  end if;
end $$;
